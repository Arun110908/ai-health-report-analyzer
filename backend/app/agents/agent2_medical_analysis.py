"""
Agent 2 -- Medical Analysis Agent

Responsibilities:
  - Retrieve medical knowledge (RAG over the curated WHO / NIH / Mayo
    Clinic reference table -- see app.reference_ranges)
  - Compare blood values with reference ranges
  - Detect nutritional deficiencies
  - Identify abnormal parameters
  - Analyze possible health risks
  - Explain every blood parameter in simple language

If ANTHROPIC_API_KEY is configured, explanations/risk reasoning are
generated by Claude, grounded with the retrieved reference-range
context (a lightweight RAG pattern). Otherwise a deterministic
rule-based engine produces the same fields.
"""
