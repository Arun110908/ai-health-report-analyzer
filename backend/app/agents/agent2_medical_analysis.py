def _rule_based_analysis(state: PipelineState) -> MedicalAnalysis:
    explanations = {}
    deficiencies = []
    risks = []
    abnormal = []

    for param in state.extracted.parameters:
        canonical = normalize_parameter_name(param.name) or param.name.lower()
        explanations[param.name] = SIMPLE_EXPLANATIONS.get(
            canonical, "A standard blood test parameter compared against a healthy reference range."
        )

        if param.status in ("low", "critical_low", "high", "critical_high"):
            abnormal.append(param.name)
            severity = "severe" if "critical" in param.status else "moderate"

            if param.status in ("low", "critical_low") and canonical in DEFICIENCY_PARAMS:
                deficiencies.append(DeficiencyOrRisk(
                    title=f"Low {param.name}",
                    parameter=param.name,
                    severity=severity,
                    explanation=(f"Your {param.name} ({param.value} {param.unit or ''}) is below the "
                                 f"healthy reference range, which may indicate a deficiency. "
                                 f"{SIMPLE_EXPLANATIONS.get(canonical, '')}"),
                ))
            else:
                direction = "below" if "low" in param.status else "above"
                risks.append(DeficiencyOrRisk(
                    title=f"{param.name} out of range",
                    parameter=param.name,
                    severity=severity,
                    explanation=(f"Your {param.name} ({param.value} {param.unit or ''}) is {direction} "
                                 f"the healthy reference range. {SIMPLE_EXPLANATIONS.get(canonical, '')}"),
                ))

    return MedicalAnalysis(
        parameter_explanations=explanations,
        deficiencies=deficiencies,
        health_risks=risks,
        abnormal_parameters=abnormal,
        sources_consulted=sorted({
            get_reference(normalize_parameter_name(p.name))["source"]
            for p in state.extracted.parameters
            if normalize_parameter_name(p.name) and get_reference(normalize_parameter_name(p.name))
        }),
    )


def _build_llm_context(state: PipelineState) -> str:
    lines = []
    for p in state.extracted.parameters:
        canonical = normalize_parameter_name(p.name)
        ref = get_reference(canonical) if canonical else None
        ref_str = f"{ref['low']}-{ref['high']} {ref['unit']} (source: {ref['source']})" if ref else "no reference on file"
        lines.append(f"- {p.name}: {p.value} {p.unit or ''} | status={p.status} | reference={ref_str}")
    return "\n".join(lines)


def run(state: PipelineState) -> PipelineState:
    if not state.extracted or not state.extracted.parameters:
        state.analysis = MedicalAnalysis()
        return state

    if claude_client.available:
        context = _build_llm_context(state)
        patient_note = ""
        if state.patient_info:
            patient_note = f"Patient context: {state.patient_info.model_dump()}"
        system = (
            "You are a careful medical-information assistant grounded strictly in the "
            "reference-range data provided. Never invent lab values. Explain in simple, "
            "friendly language a non-medical person can understand. Return ONLY valid JSON "
            "matching this schema: {\"parameter_explanations\": {name: string}, "
            "\"deficiencies\": [{\"title\":str,\"parameter\":str,\"severity\":str,\"explanation\":str}], "
            "\"health_risks\": [{\"title\":str,\"parameter\":str,\"severity\":str,\"explanation\":str}], "
            "\"abnormal_parameters\": [str]}"
        )
        user = f"Blood parameters with status:\n{context}\n\n{patient_note}"
        result = claude_client.complete_json(system, user)
        if result:
            try:
                analysis = MedicalAnalysis(
                    parameter_explanations=result.get("parameter_explanations", {}),
                    deficiencies=[DeficiencyOrRisk(**d) for d in result.get("deficiencies", [])],
                    health_risks=[DeficiencyOrRisk(**r) for r in result.get("health_risks", [])],
                    abnormal_parameters=result.get("abnormal_parameters", []),
                    sources_consulted=["WHO", "NIH", "Mayo Clinic (via curated reference set)"],
                )
                state.analysis = analysis
                return state
            except Exception:  # noqa: BLE001
                pass  # fall through to rule-based

    state.analysis = _rule_based_analysis(state)
    return state
